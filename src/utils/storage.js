/**
 * Load all workouts, optionally filtered.
 * @param {Object} filters - Optional: { type, status, dateFrom, dateTo, planId }
 * @returns {Workout[]}
 */
export function loadWorkouts(filters = {}) {
  const all = readJSON(KEYS.workouts, []);

  return all.filter(w => {
    if (filters.type     && w.type !== filters.type)       return false;
    if (filters.status   && w.status !== filters.status)   return false;
    if (filters.planId   && w.planId !== filters.planId)   return false;
    if (filters.dateFrom && w.date < filters.dateFrom)     return false;
    if (filters.dateTo   && w.date > filters.dateTo)       return false;
    return true;
  }).sort((a, b) => a.date.localeCompare(b.date));
}

/**
 * Load workouts for a specific date.
 * Returns multiple entries (e.g., a run AND a lift on the same day).
 */
export function loadWorkoutsByDate(date) {
  return loadWorkouts({ dateFrom: date, dateTo: date });
}

/**
 * Find a single workout by ID.
 */
export function loadWorkoutById(id) {
  const all = readJSON(KEYS.workouts, []);
  return all.find(w => w.id === id) || null;
}

/**
 * Save a new workout. Returns the saved workout.
 */
export function addWorkout(workout) {
  const all = readJSON(KEYS.workouts, []);
  all.push(workout);
  writeJSON(KEYS.workouts, all);
  return workout;
}

/**
 * Update an existing workout by ID. Merges the updates.
 * Automatically sets updatedAt.
 */
export function updateWorkout(id, updates) {
  const all = readJSON(KEYS.workouts, []);
  const index = all.findIndex(w => w.id === id);

  if (index === -1) {
    console.warn(`Workout ${id} not found`);
    return null;
  }

  // Deep merge details if provided
  if (updates.details) {
    updates.details = { ...all[index].details, ...updates.details };
  }

  all[index] = {
    ...all[index],
    ...updates,
    updatedAt: new Date().toISOString(),
  };

  writeJSON(KEYS.workouts, all);
  return all[index];
}

/**
 * Delete a workout by ID.
 */
export function deleteWorkout(id) {
  const all = readJSON(KEYS.workouts, []);
  const filtered = all.filter(w => w.id !== id);
  writeJSON(KEYS.workouts, filtered);
}

/**
 * Add multiple workouts at once (used by plan activation).
 */
export function addWorkoutsBatch(workouts) {
  const all = readJSON(KEYS.workouts, []);
  all.push(...workouts);
  writeJSON(KEYS.workouts, all);
}


