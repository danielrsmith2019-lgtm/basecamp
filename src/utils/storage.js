export function loadPlans() {
  return readJSON(KEYS.plans, []);
}

export function loadActivePlan() {
  const plans = loadPlans();
  return plans.find(p => p.isActive) || null;
}

export function savePlan(plan) {
  const all = readJSON(KEYS.plans, []);

  // Deactivate any currently active plan if this one is being activated
  if (plan.isActive) {
    all.forEach(p => { p.isActive = false; });
  }

  const index = all.findIndex(p => p.id === plan.id);
  if (index >= 0) {
    all[index] = plan;
  } else {
    all.push(plan);
  }

  writeJSON(KEYS.plans, all);
  return plan;
}

export function deletePlan(id) {
  const all = readJSON(KEYS.plans, []);
  writeJSON(KEYS.plans, all.filter(p => p.id !== id));

  // Also remove planned workouts generated by this plan
  const workouts = readJSON(KEYS.workouts, []);
  writeJSON(
    KEYS.workouts,
    workouts.filter(w => !(w.planId === id && w.status === 'planned'))
  );
}


