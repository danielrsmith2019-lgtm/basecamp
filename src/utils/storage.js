/**
 * Converts STRIDE's trainingPlan.js array into BASECAMP workouts.
 * 
 * STRIDE format:
 * { id: 1, week: 4, date: "2026-05-13", phase: "Base Building",
 *   runType: "Tempo", runDetails: "Tempo 4 mi: ...", plannedDistance: 4,
 *   targetPace: "7:30-7:50", status: "completed", actualDistance: 4,
 *   actualTime: "31:20", actualPace: "7:50", rpe: 7, notes: "Felt strong" }
 * 
 * @param {Object[]} strideRuns - Array of STRIDE run objects
 * @returns {Workout[]} - Array of BASECAMP workout objects
 */
export function migrateStrideData(strideRuns) {
  return strideRuns.map(run => {
    // Map STRIDE status values to BASECAMP
    let status = 'planned';
    if (run.status === 'completed' || run.status === '\u2713 Done') status = 'completed';
    if (run.status === 'skipped'   || run.status === '\u2298 Skipped') status = 'skipped';

    return createRunWorkout({
      date:            run.date,
      status,
      planId:          null,  // STRIDE runs weren't plan-linked
      runType:         run.runType || 'Easy Run',
      runDescription:  run.runDetails || run.runType || '',
      phase:           run.phase || '',
      week:            run.week || 0,
      plannedDistance:  run.plannedDistance || run.distance || 0,
      targetPace:      run.targetPace || '',
      actualDistance:   run.actualDistance || null,
      actualTime:      run.actualTime || null,
      actualPace:      run.actualPace || null,
      rpe:             run.rpe || null,
      notes:           run.notes || null,
    });
  });
}


// ═══════════════════════════════════════════════════════
// MIGRATION — FITNESS APP DATA
// ═══════════════════════════════════════════════════════

/**
 * Converts the Fitness App's workout session format into BASECAMP workouts.
 * 
 * Fitness App format:
 * { id: "abc", date: "2026-05-13",
 *   exercises: [{ name: "Bench Press", muscleGroup: "Chest",
 *     sets: [{ weight: 185, reps: 8, rpe: 7 }] }] }
 * 
 * @param {Object[]} fitnessSessions - Array of Fitness App session objects
 * @returns {Workout[]} - Array of BASECAMP workout objects
 */
export function migrateFitnessAppData(fitnessSessions) {
  return fitnessSessions.map(session => {
    // Extract unique muscle groups from exercises
    const muscleGroups = [...new Set(
      (session.exercises || []).map(e => e.muscleGroup).filter(Boolean)
    )];

    // Guess session name from muscle groups
    const sessionName = muscleGroups.length > 0
      ? muscleGroups.join(' / ')
      : 'Workout';

    // Convert sets to BASECAMP format (add setNumber and completed flag)
    const exercises = (session.exercises || []).map(exercise => ({
      name:        exercise.name,
      muscleGroup: exercise.muscleGroup || 'Unknown',
      equipment:   exercise.equipment || 'Unknown',
      sets:        (exercise.sets || []).map((set, i) => ({
        setNumber:    i + 1,
        targetWeight: null,
        targetReps:   null,
        weight:       set.weight || null,
        reps:         set.reps || null,
        rpe:          set.rpe || null,
        completed:    !!(set.weight && set.reps),
      })),
    }));

    // Calculate total volume
    const { totalVolume, totalSets } = calculateLiftVolume(exercises);

    return createLiftWorkout({
      date:         session.date,
      status:       'completed', // Fitness App only saved completed sessions
      planId:       null,
      sessionName,
      muscleGroups,
      exercises,
      totalVolume,
      totalSets,
      duration:     session.duration || null,
      notes:        session.notes || null,
    });
  });
}


// ═══════════════════════════════════════════════════════
// MIGRATION — RUN BOTH
// ═══════════════════════════════════════════════════════

/**
 * One-click migration: reads old data from both apps' localStorage keys,
 * converts to BASECAMP format, and saves. Non-destructive — doesn't
 * delete the old keys so you can re-migrate if needed.
 * 
 * Call this from a "Import Existing Data" button in settings.
 * 
 * @returns {{ runs: number, lifts: number }} Count of imported entries
 */
export function migrateAllLegacyData() {
  let runCount = 0;
  let liftCount = 0;

  // ── STRIDE data ──
  // STRIDE stored runs under various possible keys
  const strideKeys = ['stride_runs', 'stride-runs', 'trainingPlan'];
  for (const key of strideKeys) {
    const raw = localStorage.getItem(key);
    if (raw) {
      try {
        const strideRuns = JSON.parse(raw);
        if (Array.isArray(strideRuns) && strideRuns.length > 0) {
          const converted = migrateStrideData(strideRuns);
          const existing = readJSON(KEYS.workouts, []);
          // Avoid duplicates by checking dates + type
          const existingKeys = new Set(existing.map(w => `${w.date}_${w.type}`));
          const newEntries = converted.filter(w => !existingKeys.has(`${w.date}_${w.type}`));
          existing.push(...newEntries);
          writeJSON(KEYS.workouts, existing);
          runCount += newEntries.length;
          break; // Found STRIDE data, stop checking other keys
        }
      } catch (e) {
        console.warn(`Failed to parse STRIDE data from key "${key}":`, e);
      }
    }
  }

  // ── Fitness App data ──
  const fitnessKeys = ['workouts', 'fitness_workouts', 'workout_history'];
  for (const key of fitnessKeys) {
    const raw = localStorage.getItem(key);
    if (raw) {
      try {
        const sessions = JSON.parse(raw);
        if (Array.isArray(sessions) && sessions.length > 0) {
          const converted = migrateFitnessAppData(sessions);
          const existing = readJSON(KEYS.workouts, []);
          const existingKeys = new Set(existing.map(w => `${w.date}_${w.type}`));
          const newEntries = converted.filter(w => !existingKeys.has(`${w.date}_${w.type}`));
          existing.push(...newEntries);
          writeJSON(KEYS.workouts, existing);
          liftCount += newEntries.length;
          break;
        }
      } catch (e) {
        console.warn(`Failed to parse Fitness App data from key "${key}":`, e);
      }
    }
  }

  // Mark migration as done
  localStorage.setItem('basecamp_migrated', 'true');

  return { runs: runCount, lifts: liftCount };
}

/**
 * Check if legacy data exists that could be migrated.
 */
export function hasLegacyData() {
  const allKeys = ['stride_runs', 'stride-runs', 'trainingPlan',
                   'workouts', 'fitness_workouts', 'workout_history'];
  return allKeys.some(key => localStorage.getItem(key) !== null);
}

/**
 * Check if migration has already been performed.
 */
export function hasMigrated() {
  return localStorage.getItem('basecamp_migrated') === 'true';
}


