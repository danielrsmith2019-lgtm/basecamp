/**
 * Exports ALL BASECAMP data as a single JSON object.
 * Used for backup before destructive operations.
 */
export function exportAllData() {
  return {
    version:   CURRENT_VERSION,
    exported:  new Date().toISOString(),
    workouts:  readJSON(KEYS.workouts, []),
    plans:     readJSON(KEYS.plans, []),
    nutrition: readJSON(KEYS.nutrition, []),
    settings:  readJSON(KEYS.settings, createDefaultSettings()),
  };
}

/**
 * Imports data from a backup JSON object.
 * Validates the structure before writing.
 */
export function importAllData(data) {
  if (!data || typeof data !== 'object') {
    throw new Error('Invalid backup file: not an object');
  }
  if (!Array.isArray(data.workouts)) {
    throw new Error('Invalid backup file: missing workouts array');
  }

  writeJSON(KEYS.workouts,  data.workouts  || []);
  writeJSON(KEYS.plans,     data.plans     || []);
  writeJSON(KEYS.nutrition, data.nutrition  || []);
  writeJSON(KEYS.settings,  data.settings  || createDefaultSettings());
  writeJSON(KEYS.version,   data.version   || CURRENT_VERSION);
}

/**
 * Nuclear option: wipes all BASECAMP data.
 * Does NOT touch legacy STRIDE or Fitness App keys.
 */
export function clearAllData() {
  Object.values(KEYS).forEach(key => localStorage.removeItem(key));
  localStorage.removeItem('basecamp_migrated');
}


// ═══════════════════════════════════════════════════════
// LOW-LEVEL HELPERS (private to this file)
// ═══════════════════════════════════════════════════════

function readJSON(key, fallback) {
  if (typeof window === 'undefined') return fallback; // SSR safety for Next.js

  try {
    const raw = localStorage.getItem(key);
    return raw ? JSON.parse(raw) : fallback;
  } catch (e) {
    console.warn(`Failed to read localStorage key "${key}":`, e);
    return fallback;
  }
}

function writeJSON(key, data) {
  if (typeof window === 'undefined') return; // SSR safety for Next.js

  try {
    localStorage.setItem(key, JSON.stringify(data));
  } catch (e) {
    console.error(`Failed to write localStorage key "${key}":`, e);
  }
}