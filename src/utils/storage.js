const KEYS = {
  workouts:   'basecamp_workouts',
  plans:      'basecamp_plans',
  nutrition:  'basecamp_nutrition',
  settings:   'basecamp_settings',
  version:    'basecamp_data_version',
};

// Current data version — bump this if you change the schema
const CURRENT_VERSION = 1;


